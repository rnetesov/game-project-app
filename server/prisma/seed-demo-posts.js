async function main() {
  const users = await prisma.user.findMany({
    select: { id: true },
    orderBy: { createdAt: 'asc' }
  });

  if (users.length === 0) {
    console.log('Нет зарегистрированных пользователей. Сначала создай аккаунт в GameHub.');
    return;
  }

  const existing = await prisma.post.findMany({
    where: { content: { in: demoPosts } },
    select: { content: true }
  });
  const existingContent = new Set(existing.map(post => post.content));
  const missing = demoPosts.filter(content => !existingContent.has(content));

  if (missing.length === 0) {
    console.log('Демонстрационные публикации уже добавлены. Повторный запуск ничего не изменил.');
    return;
  }

  const now = Date.now();
  await prisma.post.createMany({
    data: missing.map((content, index) => ({
      content,
      authorId: users[index % users.length].id,
      createdAt: new Date(now - index * 9 * 60 * 60 * 1000)
    }))
  });

  console.log(`Добавлено публикаций: ${missing.length}. Авторов в базе: ${users.length}.`);
  if (users.length === 1) {
    console.log('Сейчас в базе только один пользователь, поэтому все записи отображаются от его имени.');
  }
}

main()
  .catch(error => {
    console.error('Не удалось добавить демонстрационные публикации:', error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
